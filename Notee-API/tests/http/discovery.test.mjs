import { blocks, call, newUser, ok, summary } from './lib.mjs';
const t = await newUser('discovery');
const voter = await newUser('discovery-voter');
const handle = 'discover' + Date.now();
await call(t, 'PUT', '/me/profile', { handle, displayName: 'Autora' });
const a = (await call(t, 'POST', '/communities', { name: 'Comunidade A', description: '' })).json;
const b = (await call(t, 'POST', '/communities', { name: 'Comunidade B', description: '' })).json;
const n = (await call(t, 'POST', '/notes', { title: 'Astronomia ' + handle, content: blocks('estrelas') })).json;
const p = (await call(t, 'POST', `/notes/${n.id}/publications`, { visibility: 'public' })).json;
await call(t, 'PUT', `/communities/${a.id}/publications/${p.id}`);
await call(t, 'PUT', `/communities/${b.id}/publications/${p.id}`);
await call(voter, 'PUT', `/social/publications/${p.id}/like`);
const get = query => call(t, 'GET', '/communities/discover?' + query);
let r = await get(`communities=${a.id},${b.id}&criteria=likes,recent,reposts&q=${handle}`);
ok(r.status === 200 && r.json.length === 1, 'combina comunidades sem duplicar notas');
ok(r.json?.[0]?.score > 0 && r.json?.[0]?.score <= 1, 'pontuacao combinada normalizada');
ok((await get(`communities=${a.id}&criteria=likes&q=${handle}`)).json?.[0]?.likes === 1, 'ordena por utilidade e conta curtidas');
ok((await get(`communities=${a.id}&q=inexistente`)).json.length === 0, 'busca filtra texto');
ok((await get(`communities=${a.id}&criteria=recent&days=7`)).status === 200, 'permite periodo e criterio unico');
ok((await get('communities=invalido')).status === 400, 'valida comunidades');
ok((await get('criteria=')).status === 400, 'exige criterio');
ok((await get('criteria=invalido')).status === 400, 'valida criterios');
ok((await get('days=999')).status === 400, 'valida periodo');
await call(t, 'DELETE', `/publications/${p.id}`);
ok((await get(`communities=${a.id}&q=${handle}`)).json.length === 0, 'revogacao remove da descoberta');
process.exit(summary('Discovery'));
