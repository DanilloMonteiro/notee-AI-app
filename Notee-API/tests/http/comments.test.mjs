import { call, newUser, blocks, ok, summary } from './lib.mjs';

const owner = await newUser('discussion-owner');
const reader = await newUser('discussion-reader');
const third = await newUser('discussion-third');
const stamp = Date.now().toString(36);
await call(owner, 'PUT', '/me/profile', { handle: `writer${stamp}`, displayName: 'Autora' });
await call(reader, 'PUT', '/me/profile', { handle: `reader${stamp}`, displayName: 'Leitora' });
await call(third, 'PUT', '/me/profile', { handle: `third${stamp}`, displayName: 'Terceira' });
const note = (await call(owner, 'POST', '/notes', { title: 'Discussão', content: blocks('Trecho publicado para comentar') })).json;
const pub = (await call(owner, 'POST', `/notes/${note.id}/publications`, { visibility: 'public' })).json;
const anchor = { blockId: 'b1', exactQuote: 'Trecho publicado', startIndex: 0 };
ok((await call(reader, 'POST', `/discussion/${pub.id}`, { text: 'Não existe', anchor: { ...anchor, startIndex: 1 } })).status === 400, 'trecho inválido recusado');
let r = await call(reader, 'POST', `/discussion/${pub.id}`, { text: 'Comentário no trecho', anchor });
ok(r.status === 201, 'comentário no trecho publicado');
const commentId = r.json?.id;
r = await call(third, 'POST', `/discussion/${pub.id}`, { text: 'Resposta', parentId: commentId });
ok(r.status === 201, 'resposta em um nível');
const replyId = r.json?.id;
r = await call(owner, 'GET', `/discussion/${pub.id}?view=all`);
ok(r.json?.find(c => c.id === replyId)?.anchorQuote === anchor.exactQuote, 'resposta herda âncora');
ok((await call(reader, 'PUT', `/discussion/comments/${commentId}/like`)).status === 400, 'não curte próprio comentário');
ok((await call(owner, 'PUT', `/discussion/comments/${commentId}/like`)).status === 204, 'curtida criada');
ok((await call(owner, 'PUT', `/discussion/comments/${commentId}/like`)).status === 204, 'curtida idempotente');
r = await call(owner, 'GET', `/discussion/${pub.id}?view=top`);
ok(r.json?.find(c => c.id === commentId)?.likeCount === 1, 'contagem e visão top');
const more = [];
for (const label of ['B', 'C', 'D']) more.push((await call(third, 'POST', `/discussion/${pub.id}`, { text: label, anchor })).json?.id);
await call(owner, 'PUT', `/discussion/comments/${more[0]}/like`);
await call(reader, 'PUT', `/discussion/comments/${more[0]}/like`);
r = await call(owner, 'GET', `/discussion/${pub.id}?view=top`);
ok(r.json?.filter(c => !c.parentId).length === 3 && r.json?.find(c => c.id === more[0])?.likeCount === 2 && r.json?.find(c => c.id === more[0])?.moreCount === 1, 'top mostra três por trecho e conta restantes');
ok(r.json?.find(c => !c.parentId)?.id === more[0], 'top ordena por curtidas');
ok((await call(reader, 'POST', `/discussion/comments/${commentId}/hide`)).status === 404, 'só autor da publicação oculta');
ok((await call(owner, 'POST', `/discussion/comments/${commentId}/hide`)).status === 204, 'autor oculta');
const hiddenView = (await call(third, 'GET', `/discussion/${pub.id}`)).json;
ok(hiddenView?.find(c => c.id === commentId)?.text === '' && hiddenView?.some(c => c.id === replyId), 'oculto não expõe texto e preserva respostas');
ok((await call(owner, 'GET', `/discussion/${pub.id}`)).json?.some(c => c.id === commentId && c.hidden), 'autor vê oculto');
ok((await call(owner, 'POST', `/discussion/comments/${commentId}/unhide`)).status === 204, 'autor restaura');
const alerts = (await call(owner, 'GET', '/me/notifications')).json;
ok(alerts?.some(n => n.commentId === commentId && n.kind === 'comment'), 'aviso de comentário criado');
ok((await call(reader, 'GET', '/me/notifications')).json?.some(n => n.commentId === replyId && n.kind === 'reply'), 'aviso de resposta criado');
ok((await call(owner, 'POST', '/me/notifications/read', { ids: [alerts[0].id] })).status === 204, 'aviso marcado como lido');
ok((await call(owner, 'GET', '/me/notifications')).json?.find(n => n.id === alerts[0].id)?.readAt, 'leitura persistida');
const patched = await call(owner, 'PATCH', `/publications/${pub.id}`, { visibility: 'public', expectedVersion: pub.version, commentsEnabled: false });
ok(patched.status === 200 && patched.json.commentsEnabled === false, 'autor desliga comentários');
ok((await call(reader, 'POST', `/discussion/${pub.id}`, { text: 'Bloqueado' })).status === 409, 'comentário bloqueado');
const unlisted = (await call(owner, 'POST', `/notes/${note.id}/publications`, { visibility: 'unlisted', slug: `secret${stamp}` })).json;
ok((await call(reader, 'GET', `/discussion/${unlisted.id}`)).status === 404, 'link não listado não expõe discussão');
process.exit(summary('comments') ? 1 : 0);
