import { blocks, call, newUser, ok, summary } from './lib.mjs';
const author = await newUser('social-author');
const reader = await newUser('social-reader');
const handle = 'social' + Date.now();
await call(author, 'PUT', '/me/profile', { handle, displayName: 'Autora social' });
const note = (await call(author, 'POST', '/notes', { title: 'Conhecimento público', content: blocks('Publicado') })).json;
const pub = (await call(author, 'POST', `/notes/${note.id}/publications`, { visibility: 'public' })).json;
ok((await call(null, 'GET', '/social/feed')).status === 401, 'feed exige autenticação');
ok((await call(reader, 'GET', '/social/feed')).json.length === 0, 'feed começa vazio');
ok((await call(author, 'PUT', `/social/following/${handle}`)).status === 400, 'impede seguir a si mesmo');
await Promise.all([call(reader, 'PUT', `/social/following/${handle}`), call(reader, 'PUT', `/social/following/${handle}`)]);
ok((await call(reader, 'GET', `/social/profiles/${handle}`)).json.followers === 1, 'seguir é idempotente inclusive em concorrência');
ok((await call(reader, 'GET', '/social/feed')).json.some(p => p.id === pub.id), 'feed inclui publicação seguida');
await call(reader, 'PUT', `/social/publications/${pub.id}/like`);
await call(reader, 'PUT', `/social/publications/${pub.id}/like`);
ok((await call(reader, 'GET', '/social/feed')).json.find(p => p.id === pub.id).likes === 1, 'curtida não duplica');
ok((await call(author, 'PUT', `/social/publications/${pub.id}/like`)).status === 400, 'autor não avalia a si mesmo');
await call(reader, 'DELETE', `/social/publications/${pub.id}/like`);
ok((await call(reader, 'GET', '/social/feed')).json.find(p => p.id === pub.id).likes === 0, 'pode desfazer curtida');
await call(reader, 'PUT', `/social/publications/${pub.id}/repost`);
await call(author, 'DELETE', `/publications/${pub.id}`);
ok((await call(reader, 'GET', '/social/feed')).json.length === 0, 'revogar remove publicação e repost do feed');
ok((await call(reader, 'PUT', `/social/publications/${pub.id}/like`)).status === 404, 'não interage com publicação revogada');
const secret = (await call(author, 'POST', `/notes/${note.id}/publications`, { visibility: 'unlisted', slug: 'secreto' })).json;
ok((await call(reader, 'PUT', `/social/publications/${secret.id}/repost`)).status === 404, 'não reposta publicação não listada');
await call(reader, 'DELETE', `/social/following/${handle}`);
ok((await call(reader, 'GET', `/social/profiles/${handle}`)).json.followers === 0, 'deixar de seguir atualiza contagem');
process.exit(summary('Social'));
