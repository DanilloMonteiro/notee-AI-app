import { blocks, call, newUser, ok, summary } from './lib.mjs';
const owner = await newUser('moderation-owner');
const moderator = await newUser('moderation-mod');
const reader = await newUser('moderation-reader');
const prefix = 'mod' + Date.now();
for (const [t, suffix] of [[owner, 'o'], [moderator, 'm'], [reader, 'r']]) await call(t, 'PUT', '/me/profile', { handle: prefix + suffix, displayName: suffix });
const community = (await call(owner, 'POST', '/communities', { name: 'Debate', description: '' })).json;
await call(moderator, 'PUT', `/communities/${community.id}/membership`);
await call(reader, 'PUT', `/communities/${community.id}/membership`);
const n = (await call(owner, 'POST', '/notes', { title: 'Leitura ' + prefix, content: blocks('conteudo') })).json;
const p = (await call(owner, 'POST', `/notes/${n.id}/publications`, { visibility: 'public' })).json;
await call(owner, 'PUT', `/communities/${community.id}/publications/${p.id}`);
const reading = `/social/reading/${prefix}o/${p.slug}`;
ok((await call(owner, 'POST', reading)).json.views === 0, 'autor nao incrementa leitura');
await Promise.all([call(reader, 'POST', reading), call(reader, 'POST', reading)]);
ok((await call(reader, 'POST', reading)).json.views === 1, 'leituras concorrentes contam uma por leitor e dia');
await call(moderator, 'POST', reading);
ok((await call(reader, 'POST', reading)).json.views === 2, 'outro leitor incrementa');
const ranking = (await call(reader, 'GET', `/communities/discover?communities=${community.id}&criteria=views`)).json;
ok(ranking?.[0]?.views === 2 && ranking?.[0]?.score > 0, 'visualizacoes participam do ranking');
const root = (await call(reader, 'POST', `/discussion/${p.id}`, { text: 'Pergunta' })).json;
const reply = await call(moderator, 'POST', `/discussion/${p.id}`, { text: 'Resposta', parentId: root.id });
ok(reply.status === 201, 'permite resposta');
ok((await call(owner, 'POST', `/discussion/${p.id}`, { text: 'Nivel tres', parentId: reply.json.id })).status === 400, 'impede terceiro nivel');
const n2 = (await call(owner, 'POST', '/notes', { title: 'Outra leitura', content: blocks('outro') })).json;
const p2 = (await call(owner, 'POST', `/notes/${n2.id}/publications`, { visibility: 'public' })).json;
ok((await call(owner, 'POST', `/discussion/${p2.id}`, { text: 'Cruzada', parentId: root.id })).status === 400, 'impede resposta em outra publicacao');
await call(reader, 'DELETE', `/discussion/${root.id}`);
const comments = (await call(reader, 'GET', `/discussion/${p.id}`)).json;
ok(comments.find(c => c.id === root.id)?.isDeleted && comments.some(c => c.id === reply.json.id), 'exclusao preserva respostas e remove texto');
ok((await call(reader, 'PUT', `/communities/${community.id}/members/${prefix}m`, { isModerator: true, isSuspended: false })).status === 403, 'participante nao promove moderador');
ok((await call(owner, 'PUT', `/communities/${community.id}/members/${prefix}m`, { isModerator: true, isSuspended: false })).status === 204, 'criador promove moderador');
ok((await call(moderator, 'DELETE', `/communities/${community.id}/publications/${p.id}`)).status === 204, 'moderador remove vinculo de nota alheia');
ok((await call(moderator, 'PUT', `/communities/${community.id}/members/${prefix}r`, { isModerator: false, isSuspended: true })).status === 403, 'moderador nao altera membros');
ok((await call(owner, 'PUT', `/communities/${community.id}/members/${prefix}r`, { isModerator: false, isSuspended: true })).status === 204, 'criador suspende participante');
await call(reader, 'DELETE', `/communities/${community.id}/membership`);
ok((await call(reader, 'PUT', `/communities/${community.id}/membership`)).status === 403, 'sair e entrar nao contorna suspensao');
ok((await call(owner, 'PUT', `/communities/${community.id}/members/${prefix}o`, { isModerator: false, isSuspended: true })).status === 400, 'criador nao suspende a si mesmo');
await call(owner, 'PUT', `/communities/${community.id}/members/${prefix}r`, { isModerator: false, isSuspended: false });
ok((await call(reader, 'GET', `/communities/${community.id}`)).json.joined, 'restaurar acesso reativa participacao');
await call(owner, 'DELETE', `/publications/${p.id}`);
ok((await call(reader, 'POST', reading)).status === 404, 'revogada nao recebe novas leituras');
await call(owner, 'POST', `/notes/${n.id}/trash`, { expectedVersion: n.version });
ok((await call(owner, 'DELETE', `/notes/${n.id}`)).status === 204, 'exclusao definitiva remove notas com respostas');
process.exit(summary('Moderation and reading'));
