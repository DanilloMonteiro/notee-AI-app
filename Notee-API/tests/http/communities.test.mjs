import { blocks, call, newUser, ok, summary } from './lib.mjs';
const owner = await newUser('community');
const other = await newUser('participant');
const handle = 'community' + Date.now();
await call(owner, 'PUT', '/me/profile', { handle, displayName: 'Autora' });
await call(other, 'PUT', '/me/profile', { handle: handle + 'b', displayName: 'Participante' });
const community = (await call(owner, 'POST', '/communities', { name: 'Ciencia', description: 'Notas de estudo' })).json;
ok((await call(null, 'GET', '/communities')).status === 401, 'comunidades exigem login');
ok((await call(owner, 'POST', '/communities', { name: '', description: '' })).status === 400, 'valida nome');
ok((await call(owner, 'GET', `/communities/${community.id}`)).json.isOwner, 'criador administra comunidade');
const note = (await call(owner, 'POST', '/notes', { title: 'Ciencia aberta', content: blocks('publicado') })).json;
const pub = (await call(owner, 'POST', `/notes/${note.id}/publications`, { visibility: 'public' })).json;
ok((await call(other, 'PUT', `/communities/${community.id}/publications/${pub.id}`)).status === 403, 'exige participacao');
await call(other, 'PUT', `/communities/${community.id}/membership`);
ok((await call(other, 'PUT', `/communities/${community.id}/publications/${pub.id}`)).status === 404, 'nao vincula publicacao alheia');
await call(owner, 'PUT', `/communities/${community.id}/publications/${pub.id}`);
await call(owner, 'PUT', `/communities/${community.id}/publications/${pub.id}`);
ok((await call(other, 'GET', `/communities/${community.id}/notes`)).json.length === 1, 'vinculo idempotente');
ok((await call(other, 'GET', `/communities/${community.id}/notes?sort=invalido`)).status === 400, 'rejeita ordenacao invalida');
const comment = await call(other, 'POST', `/discussion/${pub.id}`, { text: 'Gostei desta abordagem.' });
ok(comment.status === 201, 'participante comenta');
const comments = (await call(owner, 'GET', `/discussion/${pub.id}`)).json;
ok(comments.length === 1 && comments[0].revisionId, 'discussao registra versao publicada');
ok((await call(owner, 'DELETE', `/discussion/${comment.json.id}`)).status === 404, 'nao exclui comentario alheio');
ok((await call(other, 'DELETE', `/discussion/${comment.json.id}`)).status === 204, 'autor exclui comentario proprio');
const secret = (await call(owner, 'POST', `/notes/${note.id}/publications`, { visibility: 'unlisted', slug: 'naolistada' })).json;
ok((await call(owner, 'PUT', `/communities/${community.id}/publications/${secret.id}`)).status === 404, 'comunidade nao aceita nao listada');
await call(owner, 'DELETE', `/publications/${pub.id}`);
ok((await call(other, 'GET', `/communities/${community.id}/notes`)).json.length === 0, 'revogada desaparece da comunidade');
ok((await call(other, 'GET', `/discussion/${pub.id}`)).status === 404, 'revogada oculta discussao');
process.exit(summary('Communities'));
